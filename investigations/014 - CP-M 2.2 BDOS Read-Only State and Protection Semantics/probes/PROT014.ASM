; Investigation 014 isolated protection probe
; Build: z80asm -fb -oPROT014.COM PROT014.ASM
	ORG 0100H
START:
	LD SP,STACKTOP
	LD A,(0080H)
	OR A
	JR Z,MODE_N
	LD A,(0082H)
	AND 05FH
	CP 'A'
	JP Z,MODE_A
	CP 'B'
	JP Z,MODE_B
	CP 'C'
	JP Z,MODE_C
	CP 'D'
	JP Z,MODE_D
	CP 'E'
	JP Z,MODE_E
	CP 'F'
	JP Z,MODE_F
	CP 'G'
	JP Z,MODE_G
	CP 'H'
	JP Z,MODE_H
	CP 'I'
	JP Z,MODE_I
	CP 'J'
	JP Z,MODE_J
	CP 'K'
	JP Z,MODE_K
MODE_N:
	LD DE,LNSTART
	CALL PUTS9
	CALL PRINTVEC
	LD C,28
	CALL 0005H
	LD DE,LNPROT
	CALL PUTS9
	CALL PRINTVEC
	LD C,13
	CALL 0005H
	LD DE,LNRESET
	CALL PUTS9
	CALL PRINTVEC
	; ATTR: set RO+SYS then clear both.
	LD HL,FATTRRS
	CALL LOADFCB
	LD C,30
	CALL CALLFCB
	LD DE,LATTRSET
	CALL REPORT
	LD HL,FATTR
	CALL LOADFCB
	LD C,30
	CALL CALLFCB
	LD DE,LATTRCLR
	CALL REPORT
	; Multi-extent: set RO; Function 30 must update all occurrences.
	LD HL,FBIGRO
	CALL LOADFCB
	LD C,30
	CALL CALLFCB
	LD DE,LBIGSET
	CALL REPORT
	; Function 30 returns FF when the unambiguous file does not exist.
	LD HL,FNOATTR
	CALL LOADFCB
	LD C,30
	CALL CALLFCB
	LD DE,LATTRMISS
	CALL REPORT
	; Make copies the high attribute bits from its FCB into the new entry.
	LD HL,FMAKEATTR
	CALL LOADFCB
	LD C,22
	CALL CALLFCB
	LD DE,LMAKEATTR
	CALL REPORT
	RET

MODE_A:
	LD A,'A'
	CALL CASEHEAD
	LD HL,FRO
	CALL OPENFCB
	LD A,'S'
	CALL FILLBUF
	LD C,21
	JP FATALCALL
MODE_B:
	LD A,'B'
	CALL CASEHEAD
	LD HL,FRO
	CALL OPENFCB
	XOR A
	LD (FCB+33),A
	LD (FCB+34),A
	LD (FCB+35),A
	LD A,'R'
	CALL FILLBUF
	LD C,34
	JP FATALCALL
MODE_C:
	LD A,'C'
	CALL CASEHEAD
	LD HL,FRO
	CALL LOADFCB
	LD C,19
	JP FATALCALL
MODE_D:
	LD A,'D'
	CALL CASEHEAD
	LD HL,RRO
	CALL LOADREN
	LD C,23
	JP FATALCALL
MODE_E:
	LD A,'E'
	CALL CASEHEAD
	LD HL,FCLOSE
	CALL OPENFCB
	LD A,'C'
	CALL FILLBUF
	LD C,21
	CALL CALLFCB
	; Save dirty FCB, mark directory entry read-only via second FCB, restore.
	LD HL,FCB
	LD DE,SAVEFCB
	LD BC,36
	LDIR
	LD HL,FCLOSERO
	CALL LOADFCB
	LD C,30
	CALL CALLFCB
	LD HL,SAVEFCB
	LD DE,FCB
	LD BC,36
	LDIR
	LD C,16
	CALL CALLFCB
	LD DE,LRETURNED
	CALL REPORT
	RET

MODE_F:
	LD A,'F'
	CALL CASEHEAD
	CALL PROTECT
	LD HL,FNEW
	CALL LOADFCB
	LD C,22
	JP FATALCALL
MODE_G:
	LD A,'G'
	CALL CASEHEAD
	LD HL,FDSK
	CALL OPENFCB
	CALL PROTECT
	LD A,'G'
	CALL FILLBUF
	LD C,21
	JP FATALCALL
MODE_H:
	LD A,'H'
	CALL CASEHEAD
	LD HL,FDSK
	CALL OPENFCB
	CALL PROTECT
	XOR A
	LD (FCB+33),A
	LD (FCB+34),A
	LD (FCB+35),A
	LD A,'H'
	CALL FILLBUF
	LD C,34
	JP FATALCALL
MODE_I:
	LD A,'I'
	CALL CASEHEAD
	CALL PROTECT
	LD HL,FDSK
	CALL LOADFCB
	LD C,19
	JP FATALCALL
MODE_J:
	LD A,'J'
	CALL CASEHEAD
	CALL PROTECT
	LD HL,RDSK
	CALL LOADREN
	LD C,23
	JP FATALCALL
MODE_K:
	LD A,'K'
	CALL CASEHEAD
	CALL PRINTVEC
	LD C,28
	CALL 0005H
	LD DE,LAFTER28
	CALL PUTS9
	CALL PRINTVEC
	LD C,13
	CALL 0005H
	LD DE,LAFTER13
	CALL PUTS9
	CALL PRINTVEC
	LD C,25
	CALL 0005H
	LD (RESULT),A
	LD DE,LCURRENT
	CALL REPORT
	RET

PROTECT:
	LD C,28
	CALL 0005H
	LD DE,LPROTECTED
	CALL PUTS9
	CALL PRINTVEC
	RET
FATALCALL:
	PUSH BC
	LD DE,LBEFORE
	CALL REPORT
	POP BC
	CALL CALLFCB
	LD DE,LRETURNED
	CALL REPORT
	RET

CASEHEAD:
	LD (CASECHAR),A
	LD DE,LCASE
	CALL PUTS9
	LD A,(CASECHAR)
	CALL PUTC
	CALL CRLF
	RET
PRINTVEC:
	LD C,29
	CALL 0005H
	PUSH HL
	LD DE,LVECTOR
	CALL PUTS9
	POP HL
	LD A,H
	CALL HEXBYTE
	LD A,L
	CALL HEXBYTE
	CALL CRLF
	RET
OPENFCB:
	CALL LOADFCB
	LD C,15
	CALL CALLFCB
	XOR A
	LD (FCB+32),A
	RET
CALLFCB:
	LD DE,FCB
	CALL 0005H
	LD (RESULT),A
	RET
LOADFCB:
	LD DE,FCB
	LD BC,16
	LDIR
	XOR A
	LD HL,FCB+16
	LD B,20
LF0: LD (HL),A
	INC HL
	DJNZ LF0
	RET
LOADREN:
	LD DE,FCB
	LD BC,32
	LDIR
	XOR A
	LD HL,FCB+32
	LD B,4
LR0: LD (HL),A
	INC HL
	DJNZ LR0
	RET
FILLBUF:
	LD HL,BUF
	LD (HL),A
	INC HL
	LD B,127
	XOR A
FB0: LD (HL),A
	INC HL
	DJNZ FB0
	LD DE,BUF
	LD C,26
	CALL 0005H
	RET

REPORT:
	PUSH DE
	LD C,25
	CALL 0005H
	LD (CURDISK),A
	POP HL
	CALL PUTS
	LD A,(RESULT)
	CALL HEXBYTE
	LD A,' '
	CALL PUTC
	LD A,(CURDISK)
	CALL HEXBYTE
	LD A,' '
	CALL PUTC
	LD HL,FCB
	LD B,36
RD0: LD A,(HL)
	INC HL
	PUSH HL
	CALL HEXBYTE
	LD A,' '
	CALL PUTC
	POP HL
	DJNZ RD0
	LD A,(BUF)
	CALL HEXBYTE
	CALL CRLF
	RET
PUTS9:
	LD C,9
	CALL 0005H
	RET
PUTS: LD A,(HL)
	INC HL
	OR A
	RET Z
	CALL PUTC
	JR PUTS
PUTC:
	PUSH BC
	PUSH DE
	PUSH HL
	LD E,A
	LD C,2
	CALL 0005H
	POP HL
	POP DE
	POP BC
	RET
CRLF:
	LD A,13
	CALL PUTC
	LD A,10
	JP PUTC
HEXBYTE:
	PUSH AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL NIBBLE
	POP AF
NIBBLE:
	AND 0FH
	ADD A,'0'
	CP '9'+1
	JR C,NOUT
	ADD A,7
NOUT: JP PUTC

; FCB templates. High bits in type bytes encode t1'=RO, t2'=SYS, t3'=reserved.
FATTR: DB 0,'ATTR    ','DAT',0,0,0,0
FATTRRS: DB 0,'ATTR    ',0C4H,0C1H,'T',0,0,0,0
FBIGRO: DB 0,'BIG     ',0C4H,'AT',0,0,0,0
FNOATTR: DB 0,'NOATTR  ',0C4H,'AT',0,0,0,0
FMAKEATTR: DB 0,'MADEATTR',0C4H,0C1H,'T',0,0,0,0
FRO: DB 0,'ROFILE  ','DAT',0,0,0,0
FCLOSE: DB 0,'CLOSEME ','DAT',0,0,0,0
FCLOSERO: DB 0,'CLOSEME ',0C4H,'AT',0,0,0,0
FNEW: DB 0,'NEWFILE ','DAT',0,0,0,0
FDSK: DB 0,'DSKFILE ','DAT',0,0,0,0
RRO: DB 0,'ROFILE  ','DAT',0,0,0,0, 0,'ROREN   ','DAT',0,0,0,0
RDSK: DB 0,'DSKFILE ','DAT',0,0,0,0, 0,'DSKREN  ','DAT',0,0,0,0

LNSTART: DB 'NORMAL initial',13,10,'$'
LNPROT: DB 'NORMAL after28',13,10,'$'
LNRESET: DB 'NORMAL after13',13,10,'$'
LCASE: DB 'CASE $'
LVECTOR: DB 'VECTOR $'
LPROTECTED: DB 'PROTECTED',13,10,'$'
LAFTER28: DB 'AFTER28',13,10,'$'
LAFTER13: DB 'AFTER13',13,10,'$'
LCURRENT: DB 'CURRENT ',0
LBEFORE: DB 'BEFORE ',0
LRETURNED: DB 'RETURNED ',0
LATTRSET: DB 'ATTR-SET ',0
LATTRCLR: DB 'ATTR-CLEAR ',0
LBIGSET: DB 'BIG-SET ',0
LATTRMISS: DB 'ATTR-MISS ',0
LMAKEATTR: DB 'MAKE-ATTR ',0

RESULT: DB 0
CURDISK: DB 0
CASECHAR: DB 0
FCB: DS 36,0
SAVEFCB: DS 36,0
BUF: DS 128,0
	DS 192
STACKTOP:
	END START
