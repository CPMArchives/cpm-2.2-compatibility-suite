 ORG 0100H
 LD (ENTSP),SP
 LD HL,0
 ADD HL,SP
 LD DE,STACKBYTES
 LD BC,8
 LDIR
 LD HL,(ENTSP)
 LD E,(HL)
 INC HL
 LD D,(HL)
 LD (RETWORD),DE
 LD SP,LOCALSTACK
 LD HL,MSG
 CALL PUTS
 LD HL,(ENTSP)
 CALL HEXW
 CALL SPACE
 LD HL,(RETWORD)
 CALL HEXW
 CALL CRLF
 LD HL,BMSG
 CALL PUTS
 LD HL,STACKBYTES
 LD B,8
SLP: LD A,(HL)
 INC HL
 CALL HEXB
 CALL SPACE
 DJNZ SLP
 CALL CRLF
 LD HL,(ENTSP)
 LD SP,HL
 RET
MSG: DB 'STACK34 ENTRY_SP RETURN_WORD ',0
BMSG: DB 'STACK_TOP_8 ',0
ENTSP: DW 0
RETWORD: DW 0
STACKBYTES: DS 8
 DS 128
LOCALSTACK:
 INCLUDE "COMMON34.INC"
 END

