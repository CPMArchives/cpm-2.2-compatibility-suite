; Investigation 010: CP/M 2.2 BDOS sequential-read probe
; Build: z80asm -fb -oREAD010.COM READ010.ASM

	ORG	0100H

START:
	LD	SP,STACKTOP
	LD	DE,HEADER
	LD	C,9
	CALL	0005H

	; Empty file, repeated EOF.
	LD	HL,FEMPTY
	CALL	OPENFCB
	LD	DE,LEMPTY1
	CALL	READREPORT
	LD	DE,LEMPTY2
	CALL	READREPORT

	; One exact 128-byte record, then repeated EOF.
	LD	HL,FONE
	CALL	OPENFCB
	LD	DE,LONE1
	CALL	READREPORT
	LD	DE,LONEEOF1
	CALL	READREPORT
	LD	DE,LONEEOF2
	CALL	READREPORT

	; Three-record file.
	LD	HL,FMULTI
	CALL	OPENFCB
	LD	DE,LMULTI1
	CALL	READREPORT
	LD	DE,LMULTI2
	CALL	READREPORT
	LD	DE,LMULTI3
	CALL	READREPORT
	LD	DE,LMULTIE
	CALL	READREPORT

	; 200 host bytes occupy two CP/M records; second is a full DMA record.
	LD	HL,FPART
	CALL	OPENFCB
	LD	DE,LPART1
	CALL	READREPORT
	LD	DE,LPART2
	CALL	READREPORT
	LD	DE,LPARTE
	CALL	READREPORT

	; Exactly 128 records. Read 127 silently, capture record 128 and EOF drift.
	LD	HL,FBOUND
	CALL	OPENFCB
	LD	B,127
	CALL	READN
	LD	DE,LBOUND128
	CALL	READREPORT
	LD	DE,LBOUNDE1
	CALL	READREPORT
	LD	DE,LBOUNDE2
	CALL	READREPORT

	; 130 records: capture last old extent, first/second new extent, then EOF.
	LD	HL,FBIG
	CALL	OPENFCB
	LD	B,127
	CALL	READN
	LD	DE,LBIG128
	CALL	READREPORT
	LD	DE,LBIG129
	CALL	READREPORT
	LD	DE,LBIG130
	CALL	READREPORT
	LD	DE,LBIGE
	CALL	READREPORT

	; Alternate DMA leaves 0080h sentinel intact.
	LD	HL,FONE
	CALL	OPENFCB
	LD	A,0E1H
	LD	(0080H),A
	LD	DE,BUF2
	CALL	SETDMA
	LD	DE,LALT
	CALL	READREPORT

	; Explicit B FCB; current A must be restored.
	LD	HL,FBFILE
	CALL	OPENFCB
	LD	DE,LEXPLB
	CALL	READREPORT

	; Read-only attribute does not prevent reading.
	LD	HL,FRO
	CALL	OPENFCB
	LD	DE,LRO
	CALL	READREPORT

	; Unopened FCB and invalid allocation state are outside documented input.
	CALL	RESETDMA
	LD	HL,FONE
	CALL	INITFCB
	LD	A,0FEH
	LD	(OPENRES),A
	LD	DE,LUNOPEN
	CALL	READREPORT
	CALL	RESETDMA
	LD	HL,FONE
	CALL	INITFCB
	LD	A,1
	LD	(FCB+15),A
	LD	A,0FEH
	LD	(OPENRES),A
	LD	DE,LINVALID
	CALL	READREPORT
	RET

; HL points to 16-byte unopened template.
OPENFCB:
	PUSH	HL
	CALL	RESETDMA
	POP	HL
	CALL	INITFCB
	LD	DE,FCB
	LD	C,15
	CALL	0005H
	LD	(OPENRES),A
	XOR	A
	LD	(FCB+32),A
	RET

INITFCB:
	LD	DE,FCB
	LD	BC,16
	LDIR
	XOR	A
	LD	HL,FCB+16
	LD	B,17
IFILL:
	LD	(HL),A
	INC	HL
	DJNZ	IFILL
	RET

RESETDMA:
	LD	DE,BUF1
	JP	SETDMA

SETDMA:
	LD	(ACTDMA),DE
	LD	C,26
	CALL	0005H
	RET

; B successful reads without reporting.
READN:
	PUSH	BC
	LD	C,20
	LD	DE,FCB
	CALL	0005H
	POP	BC
	DJNZ	READN
	RET

; DE label: fill active DMA EE, read, then print state and full record.
READREPORT:
	PUSH	DE
	LD	HL,(ACTDMA)
	LD	A,0EEH
	LD	B,128
RFILL:
	LD	(HL),A
	INC	HL
	DJNZ	RFILL
	LD	DE,FCB
	LD	C,20
	CALL	0005H
	LD	(READRES),A
	LD	C,25
	CALL	0005H
	LD	(CURDISK),A
	POP	HL
	CALL	PUTS
	LD	A,(OPENRES)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(READRES)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(CURDISK)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(0080H)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	HL,FCB
	LD	B,33
FDUMP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	FDUMP
	LD	HL,(ACTDMA)
	LD	B,128
DDUMP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	DDUMP
	CALL	CRLF
	RET

PUTC:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	C,2
	CALL	0005H
	POP	HL
	POP	DE
	POP	BC
	RET
PUTS:
	LD	A,(HL)
	INC	HL
	OR	A
	RET	Z
	LD	E,A
	CALL	PUTC
	JR	PUTS
CRLF:
	LD	E,13
	CALL	PUTC
	LD	E,10
	JP	PUTC
HEXBYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	NIBBLE
	POP	AF
NIBBLE:
	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,NIBOUT
	ADD	A,7
NIBOUT:
	LD	E,A
	JP	PUTC

; dr, name[8], type[3], ex, s1, s2, rc.
FEMPTY: DB 0,'EMPTY   ','DAT',0,0,0,0
FONE:   DB 0,'ONE     ','DAT',0,0,0,0
FMULTI: DB 0,'MULTI   ','DAT',0,0,0,0
FPART:  DB 0,'PART    ','DAT',0,0,0,0
FBOUND: DB 0,'BOUND   ','DAT',0,0,0,0
FBIG:   DB 0,'BIG     ','DAT',0,0,0,0
FBFILE: DB 2,'BFILE   ','DAT',0,0,0,0
FRO:    DB 0,'READONLY','DAT',0,0,0,0

HEADER: DB 'READ010 open read current byte0080 fcb[33] dma[128]',13,10,'$'
LEMPTY1: DB 'EMPTY-1 ',0
LEMPTY2: DB 'EMPTY-2 ',0
LONE1: DB 'ONE-1   ',0
LONEEOF1: DB 'ONE-EOF1',0
LONEEOF2: DB 'ONE-EOF2',0
LMULTI1: DB 'MULTI-1 ',0
LMULTI2: DB 'MULTI-2 ',0
LMULTI3: DB 'MULTI-3 ',0
LMULTIE: DB 'MULTI-EOF',0
LPART1: DB 'PART-1  ',0
LPART2: DB 'PART-2  ',0
LPARTE: DB 'PART-EOF',0
LBOUND128: DB 'BOUND-128',0
LBOUNDE1: DB 'BOUND-EOF1',0
LBOUNDE2: DB 'BOUND-EOF2',0
LBIG128: DB 'BIG-128 ',0
LBIG129: DB 'BIG-129 ',0
LBIG130: DB 'BIG-130 ',0
LBIGE: DB 'BIG-EOF ',0
LALT: DB 'ALT-DMA ',0
LEXPLB: DB 'EXPLICIT-B',0
LRO: DB 'READONLY',0
LUNOPEN: DB 'UNOPENED',0
LINVALID: DB 'INVALID ',0

ACTDMA: DW BUF1
OPENRES: DB 0
READRES: DB 0
CURDISK: DB 0
FCB: DS 36,0
BUF1: DS 128,0
BUF2: DS 128,0
	DS 128
STACKTOP:
	END	START
