; Investigation 007: BDOS disk reset, selection, and drive-state probe.
; z80asm -fb -oDSK007.COM DSK007.ASM

	ORG	0100H

START:
	LD	SP,STACKTOP
	LD	DE,BANNER
	LD	C,9
	CALL	0005H
	LD	HL,RECORDS
	LD	(RECPTR),HL
	CALL	SNAP

	LD	DE,ALTDMA
	LD	C,26
	CALL	0005H
	LD	A,0E1H
	LD	(0080H),A
	LD	A,0E2H
	LD	(ALTDMA),A
	LD	C,13
	CALL	0005H
	CALL	SNAP

	LD	E,1
	LD	C,14
	CALL	0005H
	CALL	SNAP
	LD	E,0
	LD	C,14
	CALL	0005H
	CALL	SNAP

	LD	C,28
	CALL	0005H
	CALL	SNAP
	LD	C,13
	CALL	0005H
	CALL	SNAP

	LD	DE,FCB
	LD	C,17
	CALL	0005H
	LD	(SEARCHRC),A
	CALL	SNAP

	LD	HL,LABELS
	LD	(LABPTR),HL
	LD	HL,RECORDS
	LD	(RECPTR),HL
	LD	B,7
PRLOOP:
	PUSH	BC
	LD	HL,(LABPTR)
	CALL	PUTS
	LD	(LABPTR),HL
	LD	HL,(RECPTR)
	LD	B,6
PRBYTES:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	PRBYTES
	LD	(RECPTR),HL
	CALL	CRLF
	POP	BC
	DJNZ	PRLOOP

	LD	HL,DMALABEL
	CALL	PUTS
	LD	A,(0080H)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(ALTDMA)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(SEARCHRC)
	CALL	HEXBYTE
	CALL	CRLF
	RET

; Record: F25 current, F24 low/high, 0004h, F29 low/high.
SNAP:
	LD	HL,(RECPTR)
	PUSH	HL
	LD	C,25
	CALL	0005H
	POP	DE
	LD	(DE),A
	INC	DE
	PUSH	DE
	LD	C,24
	CALL	0005H
	POP	DE
	LD	A,L
	LD	(DE),A
	INC	DE
	LD	A,H
	LD	(DE),A
	INC	DE
	LD	A,(0004H)
	LD	(DE),A
	INC	DE
	PUSH	DE
	LD	C,29
	CALL	0005H
	POP	DE
	LD	A,L
	LD	(DE),A
	INC	DE
	LD	A,H
	LD	(DE),A
	INC	DE
	LD	(RECPTR),DE
	RET

PUTC:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	C,2
	CALL	0005H
	POP	HL
	POP	DE
	POP	BC
	RET

PUTS:
	LD	A,(HL)
	INC	HL
	OR	A
	RET	Z
	LD	E,A
	CALL	PUTC
	JR	PUTS

CRLF:
	LD	E,0DH
	CALL	PUTC
	LD	E,0AH
	JP	PUTC

HEXBYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	NIBBLE
	POP	AF
NIBBLE:
	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,NIBOUT
	ADD	A,7
NIBOUT:
	LD	E,A
	JP	PUTC

BANNER:	DB	'DSK007 cur loglo loghi pz04 rolo rohi',13,10,'$'
LABELS:	DB	'ENTRY  ',0,'RESET1 ',0,'SELECTB',0,'SELECTA',0
	DB	'RO-A   ',0,'RESET2 ',0,'IMPL-B ',0
DMALABEL: DB	'DMA80 ALT SEARCHRC ',0

FCB:	DB	2
	DB	'???????????'
	DS	24,0
RECPTR:	DW	0
LABPTR:	DW	0
SEARCHRC: DB	0
RECORDS: DS	42,0
ALTDMA:	DS	128,0E2H
	DS	64
STACKTOP:
	END	START
