; Investigation 011: CP/M 2.2 sequential write and make probe
; Build: z80asm -fb -oWRITE011.COM WRITE011.ASM

	ORG	0100H

START:
	LD	SP,STACKTOP
	LD	DE,HEADER
	LD	C,9
	CALL	0005H

	; New file: visibility before write, after write, and after close.
	LD	HL,FNEW
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LMAKENEW
	CALL	REPORT
	LD	HL,FNEW
	LD	DE,LSEARCH0
	CALL	SEARCHREPORT
	LD	A,'A'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LWRITE1
	CALL	REPORT
	LD	HL,FNEW
	LD	DE,LSEARCH1
	CALL	SEARCHREPORT
	CALL	CLOSECALL
	LD	DE,LCLOSE1
	CALL	REPORT
	LD	HL,FNEW
	LD	DE,LSEARCH2
	CALL	SEARCHREPORT
	LD	HL,FNEW
	CALL	OPENFCB
	CALL	READCALL
	LD	DE,LREOPEN1
	CALL	REPORT

	; Existing name and wildcard are outside Make's documented precondition.
	LD	HL,FNEW
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LMAKEEX
	CALL	REPORT
	CALL	CLOSECALL
	LD	HL,FWILD
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LMAKEWILD
	CALL	REPORT
	CALL	CLOSECALL

	; Three records, close, reopen, and verify first record.
	LD	HL,FMULTI
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	A,'M'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LMULTI1
	CALL	REPORT
	LD	A,'N'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	A,'O'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LMULTI3
	CALL	REPORT
	CALL	CLOSECALL
	LD	DE,LMULTIC
	CALL	REPORT
	LD	HL,FMULTI
	CALL	OPENFCB
	CALL	READCALL
	LD	DE,LMULTIR
	CALL	REPORT

	; 129 records: report the full-extent transition and new extent.
	LD	HL,FBIG
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	A,'X'
	CALL	FILLBUF1
	LD	B,127
BIGLOOP:
	PUSH	BC
	CALL	WRITECALL
	POP	BC
	DJNZ	BIGLOOP
	LD	A,'Z'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LBIG128
	CALL	REPORT
	LD	A,'Q'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LBIG129
	CALL	REPORT
	CALL	CLOSECALL
	LD	DE,LBIGCLOSE
	CALL	REPORT

	; Alternate DMA.
	LD	HL,FALT
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	A,'D'
	CALL	FILLBUF2
	LD	DE,BUF2
	CALL	SETDMA
	CALL	WRITECALL
	LD	DE,LALTWRITE
	CALL	REPORT
	CALL	CLOSECALL
	LD	HL,FALT
	CALL	OPENFCB
	LD	DE,BUF1
	CALL	SETDMA
	CALL	READCALL
	LD	DE,LALTREAD
	CALL	REPORT

	; Explicit B drive create/write/close; default drive remains A.
	LD	HL,FBFILE
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LEXPLMAKE
	CALL	REPORT
	LD	A,'B'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LEXPLWRITE
	CALL	REPORT
	LD	B,127
BLOOP:
	PUSH	BC
	CALL	WRITECALL
	POP	BC
	DJNZ	BLOOP
	LD	DE,LEXPL128
	CALL	REPORT
	CALL	WRITECALL
	LD	DE,LEXPL129
	CALL	REPORT

	; Created and written but deliberately not closed.
	LD	HL,FNOCLOSE
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	A,'U'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LNCW
	CALL	REPORT
	LD	HL,FNOCLOSE
	LD	DE,LNCS
	CALL	SEARCHREPORT

	; Unopened FCB behavior is outside the documented input contract.
	LD	HL,FINVALID
	CALL	INITFCB
	LD	A,'I'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LINVALID
	CALL	REPORT

	; C has a full directory. D has no allocatable data blocks but free slots.
	LD	HL,FCDIR
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LDIRFULL
	CALL	REPORT
	LD	HL,FDFULL
	CALL	INITFCB
	LD	C,22
	CALL	BDOSFCB
	LD	DE,LDMAKE
	CALL	REPORT
	LD	A,'F'
	CALL	FILLBUF1
	CALL	WRITECALL
	LD	DE,LDWRITE
	CALL	REPORT
	RET

BDOSFCB:
	LD	DE,FCB
	CALL	0005H
	LD	(RESULT),A
	RET

WRITECALL:
	LD	C,21
	JR	BDOSFCB
CLOSECALL:
	LD	C,16
	JR	BDOSFCB
READCALL:
	LD	C,20
	JR	BDOSFCB

OPENFCB:
	CALL	INITFCB
	LD	C,15
	CALL	BDOSFCB
	XOR	A
	LD	(FCB+32),A
	RET

INITFCB:
	PUSH	HL
	LD	DE,BUF1
	CALL	SETDMA
	POP	HL
	LD	DE,FCB
	LD	BC,16
	LDIR
	XOR	A
	LD	HL,FCB+16
	LD	B,20
INIT0:
	LD	(HL),A
	INC	HL
	DJNZ	INIT0
	RET

SETDMA:
	LD	(ACTDMA),DE
	LD	C,26
	CALL	0005H
	RET

FILLBUF1:
	LD	HL,BUF1
	JR	FILL128
FILLBUF2:
	LD	HL,BUF2
FILL128:
	LD	(HL),A
	INC	HL
	LD	B,127
	XOR	A
FILLREST:
	LD	(HL),A
	INC	HL
	DJNZ	FILLREST
	RET

; HL template, DE label. Search exact and print returned 32-byte entry.
SEARCHREPORT:
	PUSH	DE
	PUSH	HL
	LD	DE,BUF2
	CALL	SETDMA
	POP	HL
	LD	DE,SFCB
	LD	BC,16
	LDIR
	XOR	A
	LD	HL,SFCB+16
	LD	B,20
SFILL:
	LD	(HL),A
	INC	HL
	DJNZ	SFILL
	LD	DE,SFCB
	LD	C,17
	CALL	0005H
	LD	(RESULT),A
	LD	B,A
	POP	HL
	CALL	PUTS
	LD	A,(RESULT)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,B
	CP	4
	JR	NC,SNOMATCH
	RRCA
	RRCA
	RRCA
	AND	60H
	LD	E,A
	LD	D,0
	LD	HL,BUF2
	ADD	HL,DE
	LD	B,32
SDUMP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	SDUMP
SNOMATCH:
	CALL	CRLF
	LD	DE,BUF1
	JP	SETDMA

; DE label. Print result/current drive, FCB[33], DMA first 4 and last byte.
REPORT:
	PUSH	DE
	LD	C,25
	CALL	0005H
	LD	(CURDISK),A
	POP	HL
	CALL	PUTS
	LD	A,(RESULT)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	A,(CURDISK)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	HL,FCB
	LD	B,33
FDUMP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	FDUMP
	LD	HL,(ACTDMA)
	LD	B,4
DDUMP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	DDUMP
	LD	HL,(ACTDMA)
	LD	DE,127
	ADD	HL,DE
	LD	A,(HL)
	CALL	HEXBYTE
	CALL	CRLF
	RET

PUTC:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	C,2
	CALL	0005H
	POP	HL
	POP	DE
	POP	BC
	RET
PUTS:
	LD	A,(HL)
	INC	HL
	OR	A
	RET	Z
	LD	E,A
	CALL	PUTC
	JR	PUTS
CRLF:
	LD	E,13
	CALL	PUTC
	LD	E,10
	JP	PUTC
HEXBYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	NIBBLE
	POP	AF
NIBBLE:
	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,NIBOUT
	ADD	A,7
NIBOUT:
	LD	E,A
	JP	PUTC

FNEW:     DB 0,'NEW     ','DAT',0,0,0,0
FWILD:    DB 0,'W?LD    ','DAT',0,0,0,0
FMULTI:   DB 0,'MULTI   ','DAT',0,0,0,0
FBIG:     DB 0,'BIG     ','DAT',0,0,0,0
FALT:     DB 0,'ALTDMA  ','DAT',0,0,0,0
FBFILE:   DB 2,'BFILE   ','DAT',0,0,0,0
FNOCLOSE: DB 0,'NOCLOSE ','DAT',0,0,0,0
FINVALID: DB 0,'INVALID ','DAT',0,0,0,0
FCDIR:    DB 3,'NOSLOT  ','DAT',0,0,0,0
FDFULL:   DB 4,'NOSPACE ','DAT',0,0,0,0

HEADER: DB 'WRITE011 result current fcb[33] dma[0..3,127]',13,10,'$'
LMAKENEW: DB 'MAKE-NEW ',0
LSEARCH0: DB 'SEARCH-MADE ',0
LWRITE1: DB 'WRITE-ONE ',0
LSEARCH1: DB 'SEARCH-PRECLOSE ',0
LCLOSE1: DB 'CLOSE-ONE ',0
LSEARCH2: DB 'SEARCH-CLOSED ',0
LREOPEN1: DB 'REOPEN-READ ',0
LMAKEEX: DB 'MAKE-EXISTING ',0
LMAKEWILD: DB 'MAKE-WILDCARD ',0
LMULTI1: DB 'MULTI-ONE ',0
LMULTI3: DB 'MULTI-THREE ',0
LMULTIC: DB 'MULTI-CLOSE ',0
LMULTIR: DB 'MULTI-REOPEN ',0
LBIG128: DB 'BIG-128 ',0
LBIG129: DB 'BIG-129 ',0
LBIGCLOSE: DB 'BIG-CLOSE ',0
LALTWRITE: DB 'ALT-WRITE ',0
LALTREAD: DB 'ALT-REOPEN ',0
LEXPLMAKE: DB 'B-MAKE ',0
LEXPLWRITE: DB 'B-WRITE ',0
LEXPL128: DB 'B-WRITE128 ',0
LEXPL129: DB 'B-WRITE129 ',0
LNCW: DB 'NOCLOSE-WRITE ',0
LNCS: DB 'NOCLOSE-SEARCH ',0
LINVALID: DB 'INVALID-WRITE ',0
LDIRFULL: DB 'DIRFULL-MAKE ',0
LDMAKE: DB 'DISKFULL-MAKE ',0
LDWRITE: DB 'DISKFULL-WRITE ',0

RESULT: DB 0
CURDISK: DB 0
ACTDMA: DW BUF1
FCB: DS 36,0
SFCB: DS 36,0
BUF1: DS 128,0
BUF2: DS 128,0
	DS 192
STACKTOP:
	END	START
