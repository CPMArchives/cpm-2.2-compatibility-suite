; Investigation 037 Function 40 zero-fill consolidation probe.
	ORG 0100H
START:
	LD SP,STACKTOP
	LD DE,HEADER
	LD C,9
	CALL 0005H

	; Function 36 maps current EX/S2/CR to r0/r1/r2; no disk activation.
	LD HL,FONE
	CALL LOADFCB
	XOR A
	CALL SETPOS
	LD DE,LSR0
	CALL F36REPORT
	LD A,1
	CALL SETPOS
	LD DE,LSR1
	CALL F36REPORT
	LD A,127
	CALL SETPOS
	LD DE,LSR127
	CALL F36REPORT
	LD A,128
	CALL SETPOS
	LD DE,LSR128A
	CALL F36REPORT
	LD A,1
	LD (FCB+12),A
	XOR A
	LD (FCB+32),A
	LD DE,LSR128B
	CALL F36REPORT
	LD A,127
	LD (FCB+32),A
	LD DE,LSR255
	CALL F36REPORT
	LD A,2
	LD (FCB+12),A
	XOR A
	LD (FCB+32),A
	LD DE,LSR256
	CALL F36REPORT
	LD A,31
	LD (FCB+12),A
	LD A,15
	LD (FCB+14),A
	LD A,127
	LD (FCB+32),A
	LD DE,LSRMAX
	CALL F36REPORT

	; File-size shapes.
	LD HL,FEMPTY
	LD DE,LSZEMPTY
	CALL SIZEREPORT
	LD HL,FONE
	LD DE,LSZONE
	CALL SIZEREPORT
	LD HL,F127
	LD DE,LSZ127
	CALL SIZEREPORT
	LD HL,F128
	LD DE,LSZ128
	CALL SIZEREPORT
	LD HL,FBIG
	LD DE,LSZ130
	CALL SIZEREPORT

	; Random reads: first, middle, final, EOF, missing extent, empty.
	LD HL,FBIG
	CALL OPENFCB
	LD HL,0
	LD A,0
	CALL SETRR
	LD DE,LRD0
	CALL READREPORT
	LD HL,64
	LD A,0
	CALL SETRR
	LD DE,LRD64
	CALL READREPORT
	LD HL,129
	LD A,0
	CALL SETRR
	LD DE,LRD129
	CALL READREPORT
	LD HL,130
	LD A,0
	CALL SETRR
	LD DE,LRDEOF
	CALL READREPORT
	LD HL,256
	LD A,0
	CALL SETRR
	LD DE,LRDHOLE
	CALL READREPORT
	LD HL,FEMPTY
	CALL OPENFCB
	LD HL,0
	LD A,0
	CALL SETRR
	LD DE,LRDEMPTY
	CALL READREPORT

	; Overwrite and append one record to existing file.
	LD HL,FONE
	CALL OPENFCB
	LD A,'W'
	CALL FILLBUF
	LD HL,0
	LD A,0
	CALL SETRR
	LD DE,LWROVER
	CALL WRITEREPORT
	LD A,'A'
	CALL FILLBUF
	LD HL,1
	LD A,0
	CALL SETRR
	LD DE,LWRAPP
	CALL WRITEREPORT
	LD C,16
	CALL CALLFCB

	; Sparse record 10, close, size=11, hole read=1, record10 succeeds.
	LD HL,FSPARSE
	CALL MAKEFCB
	LD A,'S'
	CALL FILLBUF
	LD HL,10
	LD A,0
	CALL SETRR
	LD DE,LWR10
	CALL WRITEREPORT
	LD C,16
	CALL CALLFCB
	LD HL,FSPARSE
	LD DE,LSZ11
	CALL SIZEREPORT
	LD HL,FSPARSE
	CALL OPENFCB
	LD HL,9
	LD A,0
	CALL SETRR
	LD DE,LRDSPHOLE
	CALL READREPORT
	LD HL,10
	LD A,0
	CALL SETRR
	LD DE,LRDSP10
	CALL READREPORT

	; New extent via random write at record 128.
	LD HL,FCROSS
	CALL MAKEFCB
	LD A,'X'
	CALL FILLBUF
	LD HL,128
	LD A,0
	CALL SETRR
	LD DE,LWR128
	CALL WRITEREPORT
	LD C,16
	CALL CALLFCB
	LD HL,FCROSS
	LD DE,LSZ129
	CALL SIZEREPORT

	; Highest supported record, virtual size 65536.
	LD HL,FMAX
	CALL MAKEFCB
	LD A,'M'
	CALL FILLBUF
	LD HL,0FFFFH
	LD A,0
	CALL SETRR
	LD DE,LWRMAX
	CALL WRITEREPORT
	LD C,16
	CALL CALLFCB
	LD HL,FMAX
	LD DE,LSZMAX
	CALL SIZEREPORT

	; r2 nonzero overflow and allocation-full random write on B.
	LD HL,FONE
	CALL OPENFCB
	LD HL,0
	LD A,1
	CALL SETRR
	LD DE,LRDOVER
	CALL READREPORT
	LD HL,FBFULL
	CALL MAKEFCB
	LD A,'F'
	CALL FILLBUF
	LD HL,0
	LD A,0
	CALL SETRR
	LD DE,LWRFULL
	CALL WRITEREPORT
	RET

SETPOS:
	LD (FCB+32),A
	XOR A
	LD (FCB+12),A
	LD (FCB+14),A
	RET
F36REPORT:
	PUSH DE
	LD C,36
	CALL CALLFCB
	POP DE
	JP REPORT
SIZEREPORT:
	PUSH DE
	CALL LOADFCB
	LD C,35
	CALL CALLFCB
	POP DE
	JP REPORT
READREPORT:
	PUSH DE
	LD HL,BUF
	LD B,128
	LD A,0EEH
RRFILL: LD (HL),A
	INC HL
	DJNZ RRFILL
	LD DE,BUF
	LD C,26
	CALL 0005H
	LD C,33
	CALL CALLFCB
	POP DE
	JP REPORT
WRITEREPORT:
	PUSH DE
	LD C,40
	CALL CALLFCB
	POP DE
	JP REPORT

SETRR:
	LD (FCB+33),HL
	LD (FCB+35),A
	RET
OPENFCB:
	CALL LOADFCB
	LD C,15
	CALL CALLFCB
	RET
MAKEFCB:
	CALL LOADFCB
	LD C,22
	CALL CALLFCB
	RET
CALLFCB:
	LD DE,FCB
	CALL 0005H
	LD (RESULT),A
	RET
LOADFCB:
	LD DE,FCB
	LD BC,16
	LDIR
	XOR A
	LD HL,FCB+16
	LD B,20
LF0: LD (HL),A
	INC HL
	DJNZ LF0
	RET
FILLBUF:
	LD HL,BUF
	LD (HL),A
	INC HL
	LD B,127
	XOR A
FF0: LD (HL),A
	INC HL
	DJNZ FF0
	LD DE,BUF
	LD C,26
	CALL 0005H
	RET

REPORT:
	PUSH DE
	LD C,25
	CALL 0005H
	LD (CURDISK),A
	POP HL
	CALL PUTS
	LD A,(RESULT)
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	LD A,(CURDISK)
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	LD HL,FCB
	LD B,36
RP0: LD A,(HL)
	INC HL
	PUSH HL
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	POP HL
	DJNZ RP0
	LD A,(BUF)
	CALL HEXBYTE
	CALL CRLF
	RET
PUTC:
	PUSH BC
	PUSH DE
	PUSH HL
	LD C,2
	CALL 0005H
	POP HL
	POP DE
	POP BC
	RET
PUTS: LD A,(HL)
	INC HL
	OR A
	RET Z
	LD E,A
	CALL PUTC
	JR PUTS
CRLF: LD E,13
	CALL PUTC
	LD E,10
	JP PUTC
HEXBYTE:
	PUSH AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL NIBBLE
	POP AF
NIBBLE:
	AND 0FH
	ADD A,'0'
	CP '9'+1
	JR C,NOUT
	ADD A,7
NOUT: LD E,A
	JP PUTC

FEMPTY: DB 0,'EMPTY   ','DAT',0,0,0,0
FONE: DB 0,'ONE     ','DAT',0,0,0,0
F127: DB 0,'REC127  ','DAT',0,0,0,0
F128: DB 0,'REC128  ','DAT',0,0,0,0
FBIG: DB 0,'BIG130  ','DAT',0,0,0,0
FSPARSE: DB 0,'SPARSE  ','DAT',0,0,0,0
FCROSS: DB 0,'CROSS   ','DAT',0,0,0,0
FMAX: DB 0,'MAXREC  ','DAT',0,0,0,0
FBFULL: DB 2,'FULLWR  ','DAT',0,0,0,0

HEADER: DB 'BDOS37 F40 result current fcb[36] dma0',13,10,'$'
LSR0: DB 'SETRR-0 ',0
LSR1: DB 'SETRR-1 ',0
LSR127: DB 'SETRR-127 ',0
LSR128A: DB 'SETRR-CR128 ',0
LSR128B: DB 'SETRR-EX1 ',0
LSR255: DB 'SETRR-255 ',0
LSR256: DB 'SETRR-256 ',0
LSRMAX: DB 'SETRR-65535 ',0
LSZEMPTY: DB 'SIZE-EMPTY ',0
LSZONE: DB 'SIZE-ONE ',0
LSZ127: DB 'SIZE-127 ',0
LSZ128: DB 'SIZE-128 ',0
LSZ130: DB 'SIZE-130 ',0
LRD0: DB 'READ-0 ',0
LRD64: DB 'READ-64 ',0
LRD129: DB 'READ-129 ',0
LRDEOF: DB 'READ-EOF130 ',0
LRDHOLE: DB 'READ-NOEXT256 ',0
LRDEMPTY: DB 'READ-EMPTY ',0
LWROVER: DB 'WRITE-OVER0 ',0
LWRAPP: DB 'WRITE-APPEND1 ',0
LWR10: DB 'WRITE-SPARSE10 ',0
LSZ11: DB 'SIZE-SPARSE11 ',0
LRDSPHOLE: DB 'READ-SPARSE9 ',0
LRDSP10: DB 'READ-SPARSE10 ',0
LWR128: DB 'WRITE-128 ',0
LSZ129: DB 'SIZE-CROSS129 ',0
LWRMAX: DB 'WRITE-65535 ',0
LSZMAX: DB 'SIZE-65536 ',0
LRDOVER: DB 'READ-R2-OVER ',0
LWRFULL: DB 'WRITE-DISKFULL ',0

RESULT: DB 0
CURDISK: DB 0
FCB: DS 36,0
BUF: DS 128,0
	DS 160
STACKTOP:
	END START
