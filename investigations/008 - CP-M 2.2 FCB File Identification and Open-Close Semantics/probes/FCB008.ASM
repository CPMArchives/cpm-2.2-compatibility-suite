; Investigation 008: CP/M 2.2 FCB open/close probe
; Build: z80asm -fb -oFCB008.COM FCB008.ASM

	ORG	0100H

START:
	LD	SP,STACKTOP
	LD	DE,HEADER
	LD	C,9
	CALL	0005H

	LD	HL,FOPENA
	LD	DE,LABOA
	CALL	DOOPEN
	LD	HL,FMISSING
	LD	DE,LABMISS
	CALL	DOOPEN
	LD	HL,FWILD
	LD	DE,LABWILD
	CALL	DOOPEN
	LD	HL,FOPENB
	LD	DE,LABOB
	CALL	DOOPEN
	LD	HL,FLARGE1
	LD	DE,LABEX1
	CALL	DOOPEN

	; Open then close without any write. DRI's internal high S2 bit remains set.
	LD	HL,FCLOSE
	LD	DE,WORKFCB
	LD	BC,33
	LDIR
	LD	DE,WORKFCB
	LD	C,15
	CALL	0005H
	LD	DE,WORKFCB
	LD	C,16
	CALL	0005H
	LD	DE,LABCLEAN
	CALL	REPORT

	; Deliberately model a written FCB: clear DRI's private no-write flag and
	; change RC from one to two. This is done only on a disposable disk.
	LD	HL,FCLOSE
	LD	DE,WORKFCB
	LD	BC,33
	LDIR
	LD	DE,WORKFCB
	LD	C,15
	CALL	0005H
	LD	A,(WORKFCB+14)
	AND	7FH
	LD	(WORKFCB+14),A
	LD	A,2
	LD	(WORKFCB+15),A
	LD	DE,WORKFCB
	LD	C,16
	CALL	0005H
	LD	DE,LABDIRTY
	CALL	REPORT

	; Reopen to determine whether close persisted RC=2.
	LD	HL,FCLOSE
	LD	DE,LABREOPEN
	CALL	DOOPEN

	; A dirty FCB whose file name is absent must fail close.
	LD	HL,FMISSING
	LD	DE,WORKFCB
	LD	BC,33
	LDIR
	XOR	A
	LD	(WORKFCB+14),A
	LD	DE,WORKFCB
	LD	C,16
	CALL	0005H
	LD	DE,LABCMISS
	CALL	REPORT
	RET

; HL template, DE label
DOOPEN:
	PUSH	DE
	LD	DE,WORKFCB
	LD	BC,33
	LDIR
	LD	DE,WORKFCB
	LD	C,15
	CALL	0005H
	POP	DE
	; fall through with A return

; DE label, A result. Prints result followed by all 33 FCB bytes.
REPORT:
	LD	(RESULT),A
	EX	DE,HL
	CALL	PUTS
	LD	A,(RESULT)
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	LD	HL,WORKFCB
	LD	B,33
RLOOP:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUTC
	POP	HL
	DJNZ	RLOOP
	CALL	CRLF
	RET

PUTC:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	C,2
	CALL	0005H
	POP	HL
	POP	DE
	POP	BC
	RET
PUTS:
	LD	A,(HL)
	INC	HL
	OR	A
	RET	Z
	LD	E,A
	CALL	PUTC
	JR	PUTS
CRLF:
	LD	E,13
	CALL	PUTC
	LD	E,10
	JP	PUTC
HEXBYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	NIBBLE
	POP	AF
NIBBLE:
	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,NIBOUT
	ADD	A,7
NIBOUT:
	LD	E,A
	JP	PUTC

; FCB templates: dr, f1-f8, t1-t3, ex, s1, s2, rc, d0-d15, cr.
; Allocation and RC bytes are distinctive before open.
FOPENA: DB 0,'OPENME  ','DAT',0,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH
FMISSING: DB 0,'ABSENT  ','DAT',0,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH
FWILD: DB 0,'OP?NME  ','DAT',0,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH
FOPENB: DB 2,'BFILE   ','DAT',0,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH
FLARGE1: DB 0,'LARGE   ','DAT',1,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH
FCLOSE: DB 0,'CLOSE   ','DAT',0,0,0CCH,055H
	DS 16,0AAH
	DB 0AAH

HEADER: DB 'FCB008 result then FCB[0..32]',13,10,'$'
LABOA: DB 'OPEN-A  ',0
LABMISS: DB 'MISSING ',0
LABWILD: DB 'WILD    ',0
LABOB: DB 'OPEN-B  ',0
LABEX1: DB 'EXTENT1 ',0
LABCLEAN: DB 'CLEANCL ',0
LABDIRTY: DB 'DIRTYCL ',0
LABREOPEN: DB 'REOPEN  ',0
LABCMISS: DB 'MISSCL  ',0
RESULT: DB 0
WORKFCB: DS 33,0
	DS 96
STACKTOP:
	END	START
