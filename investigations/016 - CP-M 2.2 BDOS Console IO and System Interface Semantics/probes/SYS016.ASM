; Investigation 016 system identity, user, DMA, and console-independence probe.
; z80asm -fb -oSYS016.COM SYS016.ASM
	ORG 0100H
START:
	LD SP,STACKTOP
	CALL PATCHBIOS
	LD HL,0080H
	LD B,128
	LD A,0A5H
	CALL FILL
	LD HL,ALTDMA
	LD B,128
	LD A,05AH
	CALL FILL
	LD DE,ALTDMA
	LD C,26
	CALL 0005H

; Deterministic function 1 input/echo.
	LD HL,SCRIPT
	LD (INPTR),HL
	XOR A
	LD (CONSTVAL),A
	LD C,1
	CALL 0005H
	LD (F1RET),A

; Formatted function 2 and function 9 output.
	LD E,'2'
	LD C,2
	CALL 0005H
	LD DE,NINE
	LD C,9
	CALL 0005H

; Function 6 nonblocking input and direct output.
	LD A,0FFH
	LD (CONSTVAL),A
	LD E,0FFH
	LD C,6
	CALL 0005H
	LD (F6RET),A
	XOR A
	LD (CONSTVAL),A
	LD E,'6'
	LD C,6
	CALL 0005H

; Function 10 receives S,CR into its explicit buffer (not DMA).
	LD DE,LINEBUF
	LD C,10
	CALL 0005H

; Function 11 sees T, retains it; Function 1 consumes retained T without a
; second BIOS CONIN call.
	LD A,0FFH
	LD (CONSTVAL),A
	LD C,11
	CALL 0005H
	LD (F11RET),A
	XOR A
	LD (CONSTVAL),A
	LD C,1
	CALL 0005H
	LD (PENDRET),A

; Version, current drive transitions, and user get/set.
	LD C,12
	CALL 0005H
	LD (VER),HL
	LD C,25
	CALL 0005H
	LD (DRIVE0),A
	LD E,1
	LD C,14
	CALL 0005H
	LD C,25
	CALL 0005H
	LD (DRIVE1),A
	LD E,0
	LD C,14
	CALL 0005H
	LD C,25
	CALL 0005H
	LD (DRIVE2),A
	LD E,0FFH
	LD C,32
	CALL 0005H
	LD (USER0),A
	LD E,5
	LD C,32
	CALL 0005H
	LD E,0FFH
	LD C,32
	CALL 0005H
	LD (USER5),A
	LD E,0
	LD C,32
	CALL 0005H

; Correctly numbered Function 35: size BIG.DAT while alternate DMA remains.
	LD DE,SIZEFCB
	LD C,35
	CALL 0005H

; Count any changes in both 128-byte sentinel regions.
	LD HL,0080H
	LD B,128
	LD A,0A5H
	CALL MISMATCH
	LD (DMA80BAD),A
	LD HL,ALTDMA
	LD B,128
	LD A,05AH
	CALL MISMATCH
	LD (ALTBAD),A
	LD A,(CONINCNT)
	LD (RESULTS+4),A
	LD A,(LINEBUF+1)
	LD (RESULTS+5),A
	LD A,(LINEBUF+2)
	LD (RESULTS+6),A
	LD HL,(VER)
	LD (RESULTS+7),HL
	LD A,(DMA80BAD)
	LD (RESULTS+14),A
	LD A,(ALTBAD)
	LD (RESULTS+15),A
	; A subsequent file read must still use the alternate DMA selected before
	; all console/system calls.
	LD DE,READFCB
	LD C,15
	CALL 0005H
	XOR A
	LD (READFCB+32),A
	LD DE,READFCB
	LD C,20
	CALL 0005H
	LD A,(ALTDMA)
	LD (RESULTS+16),A
	CALL RESTBIOS

	LD DE,HEADER
	CALL PRINT9
	LD HL,RESULTS
	LD B,17
PR0:	LD A,(HL)
	INC HL
	PUSH HL
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	POP HL
	DJNZ PR0
	LD A,(SIZEFCB+33)
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	LD A,(SIZEFCB+34)
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	LD A,(SIZEFCB+35)
	CALL HEXBYTE
	CALL CRLF
	LD DE,CONLABEL
	CALL PRINT9
	LD A,(CONLEN)
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	LD HL,CONBUF
	LD B,8
PR1:	LD A,(HL)
	INC HL
	PUSH HL
	CALL HEXBYTE
	LD E,' '
	CALL PUTC
	POP HL
	DJNZ PR1
	CALL CRLF
	RET

FILL:	LD (HL),A
	INC HL
	DJNZ FILL
	RET
MISMATCH:
	LD C,0
MM0:	CP (HL)
	JR Z,MM1
	INC C
MM1:	INC HL
	DJNZ MM0
	LD A,C
	RET

PATCHBIOS:
	LD HL,(0001H)
	DEC HL
	DEC HL
	DEC HL
	LD DE,6
	ADD HL,DE
	LD (VECBASE),HL
	LD DE,SAVEVEC
	LD BC,9
	LDIR
	LD HL,(VECBASE)
	LD DE,HCONST
	CALL PUTJP
	LD DE,HCONIN
	CALL PUTJP
	LD DE,HCONOUT
	JP PUTJP
PUTJP:	LD (HL),0C3H
	INC HL
	LD (HL),E
	INC HL
	LD (HL),D
	INC HL
	RET
RESTBIOS:
	LD HL,SAVEVEC
	LD DE,(VECBASE)
	LD BC,9
	LDIR
	RET
HCONST:
	LD A,(CONSTVAL)
	RET
HCONIN:
	LD HL,CONINCNT
	INC (HL)
	LD HL,(INPTR)
	LD A,(HL)
	INC HL
	LD (INPTR),HL
	RET
HCONOUT:
	LD A,(CONLEN)
	CP 16
	JR NC,HCO1
	LD E,A
	LD D,0
	LD HL,CONBUF
	ADD HL,DE
	LD (HL),C
HCO1:	LD HL,CONLEN
	INC (HL)
	RET

PRINT9:	LD C,9
	JP 0005H
PUTC:	PUSH BC
	PUSH DE
	PUSH HL
	LD C,2
	CALL 0005H
	POP HL
	POP DE
	POP BC
	RET
CRLF:	LD E,13
	CALL PUTC
	LD E,10
	JP PUTC
HEXBYTE:
	PUSH AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL NIBBLE
	POP AF
NIBBLE:
	AND 0FH
	ADD A,'0'
	CP '9'+1
	JR C,NOUT
	ADD A,7
NOUT:	LD E,A
	JP PUTC

NINE: DB '9$'
SCRIPT: DB 'Q','R','S',13,'T'
LINEBUF: DB 8,0
	DS 8,0EEH
SIZEFCB: DB 0,'BIG     ','DAT'
	DS 24,0
READFCB: DB 0,'ATTR    ','DAT'
	DS 24,0
HEADER: DB 13,10,'SYS016 f1 f6 f11 pend conin linecnt line0 verlo verhi d0 d1 d2 u0 u5 dma80 alt readmark size',13,10,'$'
CONLABEL: DB 'CON len bytes $'
VECBASE: DW 0
SAVEVEC: DS 9
INPTR: DW 0
CONSTVAL: DB 0
CONINCNT: DB 0
CONLEN: DB 0
CONBUF: DS 16,0
RESULTS:
F1RET: DB 0
F6RET: DB 0
F11RET: DB 0
PENDRET: DB 0
	DB 0 ; filled below through aliases copied after run
DRIVE0 EQU RESULTS+9
DRIVE1 EQU RESULTS+10
DRIVE2 EQU RESULTS+11
USER0 EQU RESULTS+12
USER5 EQU RESULTS+13
	DS 12,0
VER: DW 0
DMA80BAD: DB 0
ALTBAD: DB 0
ALTDMA: DS 128,05AH
	DS 128
STACKTOP:
	END START
