; Investigation 016 real-console blocking and control-C probe.
; Modes A/B call Function 1; mode C calls Function 10 at line beginning.
	ORG 0100H
START:
	LD SP,STACKTOP
	LD A,(0082H)
	AND 05FH
	LD (MODE),A
	LD HL,0080H
	LD (HL),0A5H
	LD HL,ALTDMA
	LD (HL),05AH
	LD DE,ALTDMA
	LD C,26
	CALL 0005H
	LD DE,WAITMSG
	LD C,9
	CALL 0005H
	LD A,(MODE)
	CP 'C'
	JR Z,DOBUFFER
	LD C,1
	CALL 0005H
	LD (RESULT),A
	JR REPORT
DOBUFFER:
	LD DE,LINEBUF
	LD C,10
	CALL 0005H
	LD A,(LINEBUF+1)
	LD (RESULT),A
REPORT:
	LD DE,RETMSG
	LD C,9
	CALL 0005H
	LD A,(RESULT)
	CALL HEXBYTE
	LD E,' '
	LD C,2
	CALL 0005H
	LD A,(0080H)
	CALL HEXBYTE
	LD E,' '
	LD C,2
	CALL 0005H
	LD A,(ALTDMA)
	CALL HEXBYTE
	LD E,13
	LD C,2
	CALL 0005H
	LD E,10
	LD C,2
	CALL 0005H
	RET
HEXBYTE:
	PUSH AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL NIBBLE
	POP AF
NIBBLE:
	AND 0FH
	ADD A,'0'
	CP '9'+1
	JR C,NOUT
	ADD A,7
NOUT:	LD E,A
	LD C,2
	JP 0005H
WAITMSG: DB 13,10,'WAITING',13,10,'$'
RETMSG: DB 13,10,'RETURNED result dma80 alt $'
MODE: DB 0
RESULT: DB 0
LINEBUF: DB 8,0
	DS 8,0EEH
ALTDMA: DS 128,05AH
	DS 128
STACKTOP:
	END START
