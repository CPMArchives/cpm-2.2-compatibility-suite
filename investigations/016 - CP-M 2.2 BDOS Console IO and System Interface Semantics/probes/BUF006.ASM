; Investigation 006: BDOS function 10 buffered console input probe.
; Assemble: z80asm -fb -oBUF006.COM BUF006.ASM
;
; The temporary BIOS harness supplies scripted CONIN bytes, reports no
; asynchronously pending byte through CONST, and captures CONOUT/LIST calls.

	ORG	0100H

START:
	CALL	PATCHBIOS

	LD	HL,SEQSIM
	LD	A,8
	LD	DE,RECSIM
	CALL	RUNCASE
	LD	HL,SEQLF
	LD	A,8
	LD	DE,RECLF
	CALL	RUNCASE
	LD	HL,SEQEMPTY
	LD	A,8
	LD	DE,RECEMPTY
	CALL	RUNCASE
	LD	HL,SEQFULL
	LD	A,3
	LD	DE,RECFULL
	CALL	RUNCASE
	LD	HL,SEQBS
	LD	A,8
	LD	DE,RECBS
	CALL	RUNCASE
	LD	HL,SEQDEL
	LD	A,8
	LD	DE,RECDEL
	CALL	RUNCASE
	LD	HL,SEQCE
	LD	A,8
	LD	DE,RECCE
	CALL	RUNCASE
	LD	HL,SEQCU
	LD	A,8
	LD	DE,RECCU
	CALL	RUNCASE
	LD	HL,SEQCX
	LD	A,8
	LD	DE,RECCX
	CALL	RUNCASE
	LD	HL,SEQCR
	LD	A,8
	LD	DE,RECCR
	CALL	RUNCASE
; Ctrl-P case last because DRI function 10 changes persistent printer-echo state.
	LD	HL,SEQCP
	LD	A,8
	LD	DE,RECCP
	CALL	RUNCASE

	CALL	RESTBIOS
	LD	DE,HEADER
	CALL	PRINT9
	LD	DE,LABSIM
	LD	HL,RECSIM
	CALL	PRINTREC
	LD	DE,LABLF
	LD	HL,RECLF
	CALL	PRINTREC
	LD	DE,LABEMPTY
	LD	HL,RECEMPTY
	CALL	PRINTREC
	LD	DE,LABFULL
	LD	HL,RECFULL
	CALL	PRINTREC
	LD	DE,LABBS
	LD	HL,RECBS
	CALL	PRINTREC
	LD	DE,LABDEL
	LD	HL,RECDEL
	CALL	PRINTREC
	LD	DE,LABCE
	LD	HL,RECCE
	CALL	PRINTREC
	LD	DE,LABCU
	LD	HL,RECCU
	CALL	PRINTREC
	LD	DE,LABCX
	LD	HL,RECCX
	CALL	PRINTREC
	LD	DE,LABCR
	LD	HL,RECCR
	CALL	PRINTREC
	LD	DE,LABCP
	LD	HL,RECCP
	CALL	PRINTREC
	RET

; HL=script, A=maximum, DE=record.
RUNCASE:
	LD	(INPTR),HL
	LD	(RECPTR),DE
	LD	(BUFFER),A
	LD	B,A
	INC	B		; count byte plus max data bytes
	LD	HL,BUFFER+1
	LD	A,0EEH
RCFILL:
	LD	(HL),A
	INC	HL
	DJNZ	RCFILL
	XOR	A
	LD	(CONLEN),A
	LD	(LISTLEN),A
	LD	(CONINCNT),A
	LD	DE,BUFFER
	LD	C,10
	CALL	0005H
	LD	HL,BUFFER
	LD	DE,(RECPTR)
	LD	BC,10
	LDIR
	LD	A,(CONLEN)
	LD	(DE),A
	INC	DE
	LD	HL,CONBUF
	LD	BC,24
	LDIR
	LD	A,(LISTLEN)
	LD	(DE),A
	INC	DE
	LD	A,(CONINCNT)
	LD	(DE),A
	RET

PATCHBIOS:
	LD	HL,(0001H)
	DEC	HL
	DEC	HL
	DEC	HL
	LD	DE,6
	ADD	HL,DE
	LD	(VECBASE),HL
	LD	DE,SAVEVEC
	LD	BC,12
	LDIR
	LD	HL,(VECBASE)
	LD	DE,HCONST
	CALL	PUTJP
	LD	DE,HCONIN
	CALL	PUTJP
	LD	DE,HCONOUT
	CALL	PUTJP
	LD	DE,HLIST
	JP	PUTJP

PUTJP:
	LD	(HL),0C3H
	INC	HL
	LD	A,E
	LD	(HL),A
	INC	HL
	LD	A,D
	LD	(HL),A
	INC	HL
	RET

RESTBIOS:
	LD	HL,SAVEVEC
	LD	DE,(VECBASE)
	LD	BC,12
	LDIR
	RET

HCONST:
	XOR	A
	RET

HCONIN:
	LD	HL,CONINCNT
	INC	(HL)
	LD	HL,(INPTR)
	LD	A,(HL)
	INC	HL
	LD	(INPTR),HL
	RET

HCONOUT:
	LD	A,(CONLEN)
	CP	24
	JR	NC,HCOCOUNT
	LD	E,A
	LD	D,0
	LD	HL,CONBUF
	ADD	HL,DE
	LD	(HL),C
HCOCOUNT:
	LD	HL,CONLEN
	INC	(HL)
	RET

HLIST:
	LD	HL,LISTLEN
	INC	(HL)
	RET

PRINTREC:
	PUSH	HL
	CALL	PRINT9
	POP	HL
	LD	B,37
PRLOOP:
	LD	A,(HL)
	INC	HL
	PUSH	BC
	PUSH	HL
	CALL	HEXBYTE
	LD	E,' '
	CALL	PUT2
	POP	HL
	POP	BC
	DJNZ	PRLOOP
	LD	DE,CRLF
	JP	PRINT9

HEXBYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	HEXNIB
	POP	AF
HEXNIB:
	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,HEXOUT
	ADD	A,7
HEXOUT:
	LD	E,A
PUT2:
	LD	C,2
	JP	0005H
PRINT9:
	LD	C,9
	JP	0005H

VECBASE: DW 0
SAVEVEC: DS 12
INPTR: DW 0
RECPTR: DW 0
CONINCNT: DB 0
CONLEN: DB 0
LISTLEN: DB 0
CONBUF: DS 24
BUFFER: DS 258

RECLEN EQU 37
RECSIM: DS RECLEN
RECLF: DS RECLEN
RECEMPTY: DS RECLEN
RECFULL: DS RECLEN
RECBS: DS RECLEN
RECDEL: DS RECLEN
RECCE: DS RECLEN
RECCU: DS RECLEN
RECCX: DS RECLEN
RECCR: DS RECLEN
RECCP: DS RECLEN

SEQSIM: DB 'A','B','C',0DH
SEQLF: DB 'A','B',0AH
SEQEMPTY: DB 0DH
SEQFULL: DB 'A','B','C'
SEQBS: DB 'A','B',08H,'C',0DH
SEQDEL: DB 'A','B',7FH,'C',0DH
SEQCE: DB 'A',05H,'B',0DH
SEQCU: DB 'A','B',15H,'C',0DH
SEQCX: DB 'A','B',18H,'C',0DH
SEQCR: DB 'A','B',12H,'C',0DH
SEQCP: DB 'A',10H,'B',0DH

HEADER: DB 13,10,'BUF006 max count data[8] conlen con[24] listlen calls',13,10,'$'
LABSIM: DB 'SIMPLE $'
LABLF: DB 'LFTERM $'
LABEMPTY: DB 'EMPTY  $'
LABFULL: DB 'FULL   $'
LABBS: DB 'BS     $'
LABDEL: DB 'DEL    $'
LABCE: DB 'CTRL-E $'
LABCU: DB 'CTRL-U $'
LABCX: DB 'CTRL-X $'
LABCR: DB 'CTRL-R $'
LABCP: DB 'CTRL-P $'
CRLF: DB 13,10,'$'

	END
